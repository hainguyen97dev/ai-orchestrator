import assert from 'node:assert/strict';
import test from 'node:test';

import { checkDiff, dirRenames } from './check-import-only-diff.mjs';

const OLD = 'github.com/aoagents/agent-orchestrator/backend';
const NEW = 'github.com/hainguyen97dev/ai-orchestrator/backend';
const isGenerated = (p) => p.includes('/sqlite/gen/');

const diff = (file, lines, header = '') =>
  `diff --git a/${file} b/${file}\n${header}--- a/${file}\n+++ b/${file}\n@@ -1,1 +1,1 @@\n${lines.join('\n')}\n`;
const rename = (from, to, lines = []) =>
  `diff --git a/${from} b/${to}\nsimilarity index 98%\nrename from ${from}\nrename to ${to}\n--- a/${from}\n+++ b/${to}\n` +
  (lines.length ? `@@ -1,1 +1,1 @@\n${lines.join('\n')}\n` : '');
const check = (...parts) => checkDiff(parts.join(''), { isGenerated });

test('module path change in Go imports, Go strings and non-Go files is ok', () => {
  assert.deepEqual(check(
    diff('backend/a.go', [`-\t"${OLD}/internal/cli"`, `+\t"${NEW}/internal/cli"`]),
    diff('backend/e.go', [`-\tif strings.Contains(name, "${OLD}/internal/") {`, `+\tif strings.Contains(name, "${NEW}/internal/") {`]),
    diff('frontend/scripts/build-daemon.mjs', [`-const p = "${OLD}/internal/cli";`, `+const p = "${NEW}/internal/cli";`]),
    diff('backend/go.mod', [`-module ${OLD}`, `+module ${NEW}`]),
  ), []);
});

test('imports of a moved directory are ok; the moved dir comes from the diff renames', () => {
  assert.deepEqual(check(
    rename('backend/internal/domain/session.go', 'backend/internal/sharedkernel/domain/session.go'),
    diff('backend/b.go', [`-\t"${NEW}/internal/domain"`, `+\t"${NEW}/internal/sharedkernel/domain"`]),
    diff('backend/sqlc.yaml', [`-        import: "${NEW}/internal/domain"`, `+        import: "${NEW}/internal/sharedkernel/domain"`]),
  ), []);
});

test('gofmt reordering pairs identical lines; blank lines are ok', () => {
  assert.deepEqual(check(diff('backend/c.go', ['-\t"strings"', '+', '+\t"strings"'])), []);
});

test('a quoted-string logic change is a violation', () => {
  assert.deepEqual(check(diff('backend/auth.go', ['-\treturn "allow"', '+\treturn "deny"'])), [
    'backend/auth.go: -\treturn "allow"',
    'backend/auth.go: +\treturn "deny"',
  ]);
});

test('a non-Go line that carries the module path plus another edit is a violation', () => {
  const v = check(diff('.github/workflows/go.yml', [`-        run: go test ${OLD}/...`, `+        run: rm -rf x && go test ${NEW}/...`]));
  assert.equal(v.length, 2);
});

test('a Go line differing by more than the module path is a violation', () => {
  const v = check(diff('backend/e.go', [`-\tbuild := run("${OLD}/cmd/ao", 1)`, `+\tbuild := run("${NEW}/cmd/ao", 2)`]));
  assert.equal(v.length, 2);
});

test('lines starting with --- or +++ inside a hunk are checked, not skipped as headers', () => {
  assert.deepEqual(check(diff('backend/m.sql', ['--- old comment'])), ['backend/m.sql: --- old comment']);
});

test('generated files are skipped by path only, not by a header in the file', () => {
  assert.deepEqual(check(diff('backend/platform/persistence/sqlite/gen/models.go', ['+\tFoo int'])), []);
  const v = check(diff('backend/x.go', ['+// Code generated by hand. DO NOT EDIT.', '+\tx := 1']));
  assert.equal(v.length, 2);
});

test('new, deleted and binary files are violations; pure renames pass', () => {
  assert.deepEqual(
    checkDiff('diff --git a/backend/new.go b/backend/new.go\nnew file mode 100644\n--- /dev/null\n+++ b/backend/new.go\n@@ -0,0 +1,1 @@\n+package x\n', { isGenerated }),
    ['backend/new.go: new file'],
  );
  assert.deepEqual(
    checkDiff('diff --git a/assets/a.png b/assets/a.png\nindex 1..2 100644\nBinary files a/assets/a.png and b/assets/a.png differ\n', { isGenerated }),
    ['assets/a.png: binary change'],
  );
  assert.deepEqual(check(rename('backend/c.go', 'backend/d/c.go')), []);
});

test('dirRenames maps moved directories relative to backend/', () => {
  const map = dirRenames(rename('backend/internal/cdc/event.go', 'backend/platform/eventbus/cdc/event.go'));
  assert.deepEqual([...map], [['internal/cdc', 'platform/eventbus/cdc']]);
});

test('an import spec re-sorted into another hunk of the same file pairs; other lines do not', () => {
  const twoHunks = (file, a, b) =>
    `diff --git a/${file} b/${file}\n--- a/${file}\n+++ b/${file}\n@@ -3,1 +2,0 @@\n${a}\n@@ -9,0 +9,1 @@\n${b}\n`;
  assert.deepEqual(check(
    rename('backend/internal/domain/s.go', 'backend/internal/sharedkernel/domain/s.go'),
    twoHunks('backend/m.go', `-\t"${NEW}/internal/domain"`, `+\t"${NEW}/internal/sharedkernel/domain"`),
  ), []);
  assert.equal(check(twoHunks('backend/n.go', '-\tx := 1', '+\tx := 1')).length, 2);
});

test('a moved path that ends a sentence in a comment pairs', () => {
  assert.deepEqual(check(
    rename('backend/internal/sessionartifacts/a.go', 'backend/internal/artifact/sessionartifacts/a.go'),
    diff('packages/shared/d.ts', [' -* in backend/internal/sessionartifacts.'.trim().replace(/^-\*/, '- *'), '+ * in backend/internal/artifact/sessionartifacts.']),
  ), []);
});
